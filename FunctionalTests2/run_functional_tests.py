"""Calculate and verify functional cases 8.1 through 13.9 from bundled inputs."""

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import platform
import shutil
import tempfile
import time

# These small matrix problems avoid unnecessary multithreaded BLAS overhead.
os.environ.setdefault("OPENBLAS_NUM_THREADS", "1")
os.environ.setdefault("OMP_NUM_THREADS", "1")

import numpy as np
import pandas as pd
import scipy

from risk545_ft2 import copulas, options, portfolios, tail_cases
from risk545_ft2.validation import CASE_IDS, normalize_groups, output_name, validate_cases

ROOT = Path(__file__).resolve().parent


def _json_default(value):
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, Path):
        return str(value)
    raise TypeError(f"Cannot serialize {type(value).__name__}")


def write_json(path, content):
    Path(path).write_text(json.dumps(content, indent=2, default=_json_default, allow_nan=False) + "\n")


def _publish(staging, output):
    """Replace a previous generated result folder after a complete calculation."""
    staging, output = Path(staging), Path(output)
    backup = None
    if output.exists():
        if not output.is_dir() or (any(output.iterdir()) and not (output / ".functionaltests2-output").is_file()):
            raise ValueError("Use an empty output directory or one generated by this program")
        backup = Path(tempfile.mkdtemp(prefix="ft2-previous-", dir=output.parent))
        try:
            output.rename(backup / "output")
        except BaseException:
            backup.rmdir()
            raise
    try:
        staging.rename(output)
    except BaseException:
        if backup is not None:
            try:
                (backup / "output").rename(output)
            except OSError as error:
                raise OSError(f"Could not restore previous results; recover them from {backup / 'output'}") from error
            backup.rmdir()
        raise
    else:
        if backup is not None:
            shutil.rmtree(backup)


def run(data_dir=ROOT / "data", reference_dir=ROOT / "reference", output_dir=ROOT / "output",
        *, simulations=100000, seed=545, groups=None):
    """Run complete requested groups, then save outputs, diagnostics and verification."""
    data, reference, output = map(lambda path: Path(path).resolve(), (data_dir, reference_dir, output_dir))
    if not isinstance(simulations, int) or isinstance(simulations, bool) or simulations < 10000:
        raise ValueError("Portfolio simulations must be an integer >= 10000")
    if not isinstance(seed, int) or isinstance(seed, bool) or seed < 0:
        raise ValueError("Seed must be a nonnegative integer")
    chosen = set(normalize_groups(groups))
    for original in (data, reference, ROOT / "source"):
        if output == original or output in original.parents or original in output.parents:
            raise ValueError("Output and source/input/reference directories must be separate")
    output.parent.mkdir(parents=True, exist_ok=True)
    started = time.perf_counter()
    cases, diagnostics = {}, {}
    builders = [({8, 9}, tail_cases.build_cases), ({10, 11}, portfolios.build_cases),
                ({12}, options.build_cases), ({13}, copulas.build_cases)]
    for coverage, build in builders:
        if chosen & coverage:
            print("Calculating groups", ", ".join(map(str, sorted(chosen & coverage))), flush=True)
            arguments = dict(simulations=simulations, seed=seed)
            if len(coverage) > 1:
                arguments["groups"] = chosen & coverage
            computed, evidence = build(data, **arguments)
            cases.update({key: frame for key, frame in computed.items() if int(key.split(".")[0]) in chosen})
            diagnostics.update(evidence)
    expected_ids = [case for case in CASE_IDS if int(case.split(".")[0]) in chosen]
    if set(cases) != set(expected_ids):
        raise AssertionError("Calculated case coverage is incomplete")
    summary, details = validate_cases(cases, diagnostics, reference)
    provenance = json.loads((ROOT / "SOURCE.json").read_text())
    report = dict(
        created_at=datetime.now(timezone.utc).isoformat(), source_commit=provenance["commit"],
        simulations=simulations, univariate_simulations=10000, seed=seed, groups=sorted(chosen),
        versions=dict(python=platform.python_version(), numpy=np.__version__, scipy=scipy.__version__, pandas=pd.__version__),
        passed=int((summary.Status == "PASS").sum()), total=len(summary),
        all_passed=bool((summary.Status == "PASS").all()),
        checks_passed=sum(record["passed"] for record in details), checks_total=len(details),
        comparisons=details, elapsed_seconds=time.perf_counter() - started,
        input_sha256={path.name: hashlib.sha256(path.read_bytes()).hexdigest() for path in sorted(data.glob("*.csv"))},
    )
    with tempfile.TemporaryDirectory(prefix="ft2-stage-", dir=output.parent) as temporary:
        staging = Path(temporary) / "results"
        staging.mkdir()
        (staging / ".functionaltests2-output").write_text("Generated functional-test outputs\n")
        for case, frame in cases.items():
            frame.to_csv(staging / output_name(case), index=False, float_format="%.17g")
            # Tests.xlsx retains older names for groups 8--12. Supply both spellings.
            if int(case.split(".")[0]) <= 12:
                frame.to_csv(staging / f"testout_{case}.csv", index=False, float_format="%.17g")
        summary.to_csv(staging / "test_summary.csv", index=False)
        write_json(staging / "diagnostics.json", diagnostics)
        write_json(staging / "test_report.json", report)
        manifest = {path.name: hashlib.sha256(path.read_bytes()).hexdigest()
                    for path in staging.iterdir() if path.is_file()}
        write_json(staging / "output_manifest.json", manifest)
        _publish(staging, output)
    print(summary.to_string(index=False), flush=True)
    print(f"{report['passed']}/{report['total']} cases passed; {report['checks_passed']}/{report['checks_total']} numerical comparisons passed")
    print("Output:", output)
    return report


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data-dir", type=Path, default=ROOT / "data")
    parser.add_argument("--reference-dir", type=Path, default=ROOT / "reference")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "output")
    parser.add_argument("--simulations", type=int, default=100000)
    parser.add_argument("--seed", type=int, default=545)
    parser.add_argument("--groups", nargs="+", type=int, choices=range(8, 14))
    arguments = parser.parse_args()
    report = run(arguments.data_dir, arguments.reference_dir, arguments.output_dir,
                 simulations=arguments.simulations, seed=arguments.seed, groups=arguments.groups)
    raise SystemExit(0 if report["all_passed"] else 1)
